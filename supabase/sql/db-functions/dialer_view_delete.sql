CREATE OR REPLACE FUNCTION public.dialer_view_delete(p_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_temp'
AS $function$
begin
  delete from dialer_saved_views where id = p_id and owner_user_id = auth.uid();
end;
$function$;
